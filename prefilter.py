"""
Быстрый локальный префильтр торговых сигналов.

Задача — без единого API-запроса отсеять обычную болтовню в чате и
пропустить дальше (на LLM-оценку и/или пуш) только сообщения, похожие на
реальный сигнал/инструкцию по сделке.

Подогнано под конкретный формат чата пользователя: это не шаблонные
"LONG BTC entry/TP/SL", а более разговорный спред/арбитражный трейдинг —
шорт на одной бирже + хедж на другой, сленг вроде "твх" (точка входа),
"сайз" (размер позиции), "адл" (риск автоматического делеверджа),
"спред"/"разрыв" между биржами, названия бирж (MEXC, Kucoin, Binance,
Bybit) кириллицей и латиницей вперемешку, опечатки ("Хеедж", "сппред").

Логика: считаем совпадения по нескольким независимым категориям
(направление сделки, жаргон спред-трейдинга, биржа/тикер, уровни цены/
стопы, плечо) и требуем минимум SIGNAL_MIN_HITS категорий. Если формат
сигналов в чате поменяется — правьте регулярки и типичные опечатки ниже.
"""

import re

# Направление сделки, включая типичные разговорные формы глагола
# ("шорчу", "лонгую", "зашортить") — простое "шорт\w*" их не ловит из-за
# чередования согласных при спряжении.
DIRECTION_RE = re.compile(
    r"\b(long|short|лонг\w*|шорт\w*|шорчу|зашорт\w*|отшорт\w*|"
    r"бай|sell|buy|покупк\w*|продаж\w*)\b",
    re.IGNORECASE,
)

# Жаргон спред/арбитражного трейдинга + типичные опечатки ("сппред",
# "Хеедж" — двойная буква вместо одной).
JARGON_RE = re.compile(
    r"\b(хе{1,2}дж\w*|захедж\w*|сп{1,2}ред\w*|разрыв\w*|адл|твх|сайз\w*|"
    r"арбитраж\w*|памп\w*|дамп\w*|плеч\w*|leverage)\b",
    re.IGNORECASE,
)

# Названия бирж — латиницей и кириллицей (частая транслитерация в чатах),
# плюс known-сервисы вроде gmgn для мониторинга токенов.
EXCHANGE_RE = re.compile(
    r"\b(mexc|kucoin|binance|bybit|okx|gate\.?io|htx|gmgn|"
    r"мекс\w*|кукоин\w*|байбит\w*|бинанс\w*|окх\w*)\b",
    re.IGNORECASE,
)

LEVELS_RE = re.compile(
    r"\b(entry|вход\w*|tp\d*|take[\s-]?profit|тейк\w*|sl|stop[\s-]?loss|"
    r"стоп\w*|цель\w*|target\w*)\b",
    re.IGNORECASE,
)

# Тикер/пара: BTC, $BTC, BTCUSDT, BTC/USDT, BTC-USDT, BTC_USDT и т.п.
# (нижний регистр тоже — "xvg" в чате пишут маленькими буквами).
TICKER_RE = re.compile(
    r"\b[A-Za-z]{2,10}[\s_/\-]?(USDT|USD|USDC|PERP|BTC|ETH)\b"
    r"|\$[A-Za-z]{2,10}\b",
    re.IGNORECASE,
)

# Числовая "лесенка" уровней/спреда — через дефис или стрелку "->"/"→",
# например "0.034 -> 0.0315" или "0.003-0.0031".
PRICE_LADDER_RE = re.compile(
    r"\d[\d.,]*\s*(?:[-–—]|->|→)\s*\d[\d.,]*"
)

# Процент разрыва/спреда, например "12%+"
PERCENT_RE = re.compile(r"\d{1,3}\s*%")

SIGNAL_MIN_HITS = 2


def looks_like_signal(text: str) -> bool:
    """Возвращает True, если сообщение похоже на торговый сигнал."""
    if not text or len(text.strip()) < 3:
        return False

    hits = 0
    for pattern in (
        DIRECTION_RE,
        JARGON_RE,
        EXCHANGE_RE,
        LEVELS_RE,
        TICKER_RE,
        PRICE_LADDER_RE,
        PERCENT_RE,
    ):
        if pattern.search(text):
            hits += 1

    return hits >= SIGNAL_MIN_HITS
